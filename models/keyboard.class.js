/**
 * Represents the Keyboard state for the game key bindings.
 *  All keys are initialized to 'false'(not pressed).
 */
class Keyboard {
  /** @type {boolean} Left arrow key*/
  LEFT = false;
  /** @type {boolean} Right arrow key*/
  RIGHT = false;
  /** @type {boolean} Up arrow key */
  UP = false;
  /** @type {boolean} Down arrow key */
  DOWN = false;
  /** @type {boolean} Space bar*/
  SPACE = false;
  /** @type {boolean} D key , for throwing*/
  D = false;
}
